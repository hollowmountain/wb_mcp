    label: string;
    /** Зачем слайд нужен покупателю — одной фразой. */
    job: string;
    /** Сколько кадра отдаём под текст. Главное фото ограничено Ozon. */
    textShare: 'минимум места' | 'не больше трети кадра' | 'до половины кадра';
