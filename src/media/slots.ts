function overlayBlock(slot: Slot, o: Overlay): string {
    const rule = SLOT_RULES[slot];
    const lines: string[] = [];

    if (o.headline) lines.push(`1. Сверху по центру — заголовок крупными заглавными: «${o.headline}».`);
    if (o.bullets?.length) {
        const items = o.bullets.map(b => `   — «${b}»`).join('\n');
        lines.push(
            `${lines.length + 1}. Слева столбиком — пункты списка, каждый в своей плашке со скруглёнными углами ` +
                `и значком-галочкой слева:\n${items}`
        );
    }
    if (o.badge) lines.push(`${lines.length + 1}. В верхнем углу — круглая печать с надписью «${o.badge}».`);
    if (o.footer) lines.push(`${lines.length + 1}. Внизу по центру — плашка с надписью заглавными: «${o.footer}».`);

    if (lines.length === 0) return 'ТЕКСТ: никаких надписей поверх изображения нет совсем.';

    return [
        `ТЕКСТ ПОВЕРХ ИЗОБРАЖЕНИЯ — вёрстка слайда «${rule.label}» карточки маркетплейса.`,
        `Текст занимает ${rule.textShare}, товар им не перекрыт.`,
        ...lines,
        'Шрифт — чистый гротеск, текст ровный, хорошо читаемый, без орфографических ошибок.'
    ].join('\n');
}

export interface PromptParts {
    slot: Slot;
    /** Описание обстановки своими словами, по-русски. */
    scene: string;
    overlay: Overlay;
    /** Необязательное уточнение, дописывается к сцене. */
    extra?: string;
}

/**
 * Собирает промт из шаблона. Человек описывает только сцену и тексты —
 * всё остальное одинаково от карточки к карточке, и как раз в этом смысл:
 * повторяемый результат получается из повторяемого запроса.
 */
export function buildPrompt(parts: PromptParts): string {
    const rule = SLOT_RULES[parts.slot];
    return [
        KEEP_PRODUCT,
        '',
        `СЦЕНА. ${parts.scene.trim()}${parts.extra ? ` ${parts.extra.trim()}` : ''}`,
        `Назначение слайда: ${rule.job}. ${rule.guidance}`,
        '',
        INTEGRATION,
        '',
        `СЪЁМКА. ${CAMERA} Кадр вертикальный, товар целиком, с воздухом сверху и снизу под текст.`,
        '',
        overlayBlock(parts.slot, parts.overlay),
        '',
        FORBID
    ].join('\n');
}

/** Человекочитаемое описание шаблона — его отдаёт инструмент media_template. */
export function describeTemplate(): string {
    const rows = SLOTS.map(slot => SLOT_RULES[slot])
        .sort((a, b) => a.order - b.order)
        .map(r => `${r.order}. ${r.label} — ${r.job}. Текста: ${r.textShare}. ${r.guidance}`);

    return [
        'ПОРЯДОК СЛАЙДОВ В КАРТОЧКЕ',
        ...rows,
        '',
        'Слайды kit и lifestyle необязательны: комплектация нужна только наборам, атмосферный кадр — по желанию.',
        '',
        'ФОРМАТЫ',
        ...Object.entries(SIZES).map(([key, s]) => `${key} — ${s.width}×${s.height}, ${s.about}`),
        '',
        'ЧТО НЕЛЬЗЯ ПИСАТЬ НА КАРТИНКЕ',
        'Цены, скидки, акции, «хит продаж», «№1», «лучший», срочность, телефоны, ссылки и соцсети,',
        'обещания лечения и гарантированного результата. Это проверяется до запуска: с такими надписями',
        'генерация не начнётся и деньги не спишутся.'
    ].join('\n');
}
