/**
 * Шаблон карточки: из каких слайдов она состоит, что на каждом обязательно
 * и что запрещено площадками.
 *
 * Зачем шаблон, если можно просто написать промт. Затем, что карточка — не
 * набор красивых картинок, а последовательность: покупатель листает её
 * сверху вниз и на каждом шаге получает ответ на следующий вопрос. Если
 * каждый менеджер придумывает порядок сам, получаются пять разных карточек
 * одного бренда. Здесь порядок задан кодом, а человек заполняет тексты.
 *
 * Второе назначение — не дать потратить деньги на брак. Модерация Wildberries
 * и Ozon отклоняет карточки с ценами, скидками, «хитом продаж» и контактами,
 * а лечебные обещания в косметике запрещены законом. Проверять это после
 * генерации поздно: деньги уже списаны. Поэтому запреты проверяются до
 * запуска, по тексту, который ляжет на картинку.
 *
 * Требования площадок сверены 11.09.2026: вертикаль 3:4, не меньше
 * 700×900 (рекомендуется от 900×1200), до 10 МБ, JPG/PNG/WebP, sRGB.
 * У Ozon инфографика на главном фото не должна занимать больше трети кадра.
 */

