/**
 * Сборка запроса на картинку.
 *
 * Здесь сознательно нет шаблона карточки. Он был: восемь слайдов с заданным
 * порядком и обязательными полями. Оказалось, что так получается одинаково,
 * но не хорошо: у каждого товара своя история, а у каждого менеджера свой
 * вкус, и рамка мешала обоим. Теперь сцену и надписи человек описывает сам,
 * свободным текстом.
 *
 * Осталось ровно три вещи, и ни одна из них не про красоту:
 *
 * 1. Товар должен остаться собой. Без этого модель перерисовывает упаковку
 *    и сочиняет на этикетке свои буквы — а это уже не фотография товара.
 * 2. Товар должен выглядеть снятым, а не наклеенным. Контактная тень,
 *    отражение, рефлексы: без них кадр читается как подделка с первого
 *    взгляда, сколько бы красивой ни была сцена.
 * 3. Надписи не должны нарушать правила площадок. Это проверяется до
 *    траты денег, потому что после генерации деньги уже списаны.
 *
 * Всё остальное — воля человека.
 */

/** Размеры под площадки. Ширина и высота кратны 16 — иначе модель откажет. */
export const SIZES = {
    wb: { width: 1200, height: 1600, about: 'вертикаль 3:4 — основной формат Wildberries и Ozon' },
    wb_hd: { width: 1536, height: 2048, about: 'та же вертикаль крупнее, для баннеров и печати' },
    square: { width: 1024, height: 1024, about: 'квадрат — для соцсетей, площадки его обрежут' }
} as const;

export type SizeKey = keyof typeof SIZES;

/**
 * Что нельзя писать на картинке.
 *
 * Первая группа — прямые запреты Wildberries и Ozon: цены, скидки,
 * превосходные степени, контакты. Вторая — обещания лечения: косметика не
 * лекарство, за такие формулировки прилетает не от площадки, а от закона.
 *
 * Проверяем только надписи, которые лягут на картинку, а не описание сцены:
 * иначе «лучший свет слева» срывал бы генерацию на слове «лучший».
 */
const BANNED: ReadonlyArray<{ pattern: RegExp; why: string }> = [
    { pattern: /скидк|распродаж|уценк|спецпредложен|акци[яию]/i, why: 'скидки и акции на картинке запрещены обеими площадками' },
    // Границу слова \b брать нельзя: в JS она считается по ASCII, и «\bцена»
    // на кириллице не срабатывает вовсе. Проверено — правило молчало.
    { pattern: /(?<![а-яё])цена(?![а-яё])|(?<![а-яё])руб(?![а-яё])|₽|(?<![а-яё])р\.\s|\d+\s*%\s*(скид|выгод)/iu, why: 'цену на картинку выносить нельзя' },
    { pattern: /хит продаж|бестселлер|№\s*1|номер один|топ[- ]?1|лидер продаж/i, why: 'превосходные степени и «№1» запрещены' },
    { pattern: /(?<![а-яё])лучш(ий|ая|ее|ие|его|ую)(?![а-яё])|самый лучший|непревзойдённ/iu, why: 'превосходные степени запрещены' },
    { pattern: /только сегодня|успей|спеши|ограниченн\w* предложен/i, why: 'срочность и призывы запрещены' },
    { pattern: /whatsapp|telegram|инстаграм|instagram|vk\.com|\bwww\.|https?:\/\/|@[a-z0-9_]{3,}/i, why: 'контакты и ссылки запрещены' },
    { pattern: /\+7\s*\(?\d{3}|\b8\s*\(?\d{3}\)?\s*\d{3}/i, why: 'телефон на картинке запрещён' },
    { pattern: /лечит|излечива|вылечи|терапевтическ\w* эффект|заменяет (врача|лекарств)/i, why: 'косметика не может обещать лечение' },
    { pattern: /гарантированн\w* результат|100\s*%\s*результат|навсегда избав/i, why: 'безусловные обещания результата запрещены' }
];

/** Возвращает список нарушений. Пустой — надписи можно ставить на картинку. */
export function checkTexts(texts: readonly string[]): string[] {
    const problems: string[] = [];
    for (const line of texts) {
        const clean = line.trim();
        if (!clean) continue;
        for (const rule of BANNED) {
            const hit = clean.match(rule.pattern);
            if (hit) problems.push(`«${clean}» — ${rule.why} (нашлось «${hit[0]}»)`);
        }
    }
    return [...new Set(problems)];
}

/** Описание запретов для человека — его отдаёт media_rules. */
