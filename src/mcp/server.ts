export function createMcpServer(actor: Actor): McpServer {
    const nepsell = inArea(actor, 'money');
    const onec = inArea(actor, 'erp');
    const media = inArea(actor, 'media');
    const server = new McpServer(
        { name: 'mcp-wb', version: '0.1.0' },
        {
            capabilities: { tools: {} },
            instructions:
                INSTRUCTIONS +
                (nepsell ? NEPSELL_INSTRUCTIONS : '') +
                (onec ? ONEC_INSTRUCTIONS : '') +
                (media ? MEDIA_INSTRUCTIONS : '')
        }
    );

    // Заслон ставится до регистрации: инструменты вне областей человека даже
    // не попадут в список, а вызов по устаревшему списку получит отказ.
    gateByAreas(server, actor);

    registerWhoAmI(server);
    registerReadTools(server, actor);
    registerWriteTools(server, actor);
    registerNepsellTools(server, actor);
    registerOnecTools(server, actor);
    registerOzonTools(server, actor);
    registerMediaTools(server, actor);

    return server;
}
